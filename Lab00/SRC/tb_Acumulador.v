`timescale 1ns/1ps

module tb_acumulador;

    // =====================================================
    // SEÑALES DEL TESTBENCH
    // =====================================================

    reg        clk;
    reg        rst;
    reg        start;
    reg [3:0]  x;

    wire [5:0] acc;
    wire       done;


    // =====================================================
    // INSTANCIA DEL CIRCUITO
    // =====================================================

    acumulador uut (

        .clk   (clk),
        .rst   (rst),
        .start (start),
        .x     (x),

        .acc   (acc),
        .done  (done)

    );


    // =====================================================
    // GENERADOR DE CLOCK
    // =====================================================

    always #3 clk = ~clk;


    // =====================================================
    // MONITOR
    // =====================================================

    initial begin

        $monitor(
            "Tiempo=%0t | rst=%b | start=%b | x=%d | state=%b | count=%d | acc=%d | done=%b",
            $time,
            rst,
            start,
            x,
            uut.state,
            uut.count,
            acc,
            done
        );

    end


    // =====================================================
    // GENERACION DEL ARCHIVO PARA GTKWave
    // =====================================================

    initial begin

        $dumpfile("wave.vcd");

        $dumpvars(0, tb_acumulador);

    end


    // =====================================================
    // PRUEBA
    // =====================================================

    initial begin

        // -------------------------------------------------
        // Valores iniciales
        // -------------------------------------------------

        clk   = 1'b0;
        rst   = 1'b1;
        start = 1'b0;
        x     = 4'd1;


        // -------------------------------------------------
        // Reset
        // -------------------------------------------------

        #12;

        rst = 1'b0;


        // -------------------------------------------------
        // INICIAR OPERACION
        // -------------------------------------------------

        #8;

        start = 1'b1;


        // start dura un ciclo
        #10;

        start = 1'b0;


        // -------------------------------------------------
        // Esperar resultado
        // -------------------------------------------------

        #80;


        // -------------------------------------------------
        // FINALIZAR SIMULACION
        // -------------------------------------------------

        $finish;

    end

endmodule